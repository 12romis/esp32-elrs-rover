// HAL розширювача портів (ADR-0003): старт — нуль першим, дві спроби, скан лише журналиться; запис байта світла.
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"
#include "ioexp_core.h"

typedef enum {
    IOEXP_WR_OK,           // записано (або запис не потрібен)
    IOEXP_WR_FAILED,       // шина не підтвердила запис; копія не змінена, автоматика повторить
    IOEXP_WR_UNAVAILABLE   // розширювач недоступний (не підтвердився на старті)
} ioexp_wr_t;

// Піднімає шину, першою операцією пише 0x00 в розширювач (до двох спроб), потім журналить скан.
// ESP_OK — розширювач підтвердився. Збій повертається як esp_err_t, без abort; ровер при цьому працює (деградація).
esp_err_t ioexp_start(void);

bool ioexp_hal_available(void);

// Останній підтверджений запис: розряд копії (false, якщо розширювач недоступний). Саме це бачить Розробник у status.
bool ioexp_hal_bit(int bit);

// Записує бажані біти світла (під маскою), якщо вони відрізняються від копії або попередній запис не вдався; розряди
// скидання далекомірів зберігаються. Потокобезпечна: байт пишуть ui і sensors по черзі під внутрішнім мʼютексом (ADR-0002).

ioexp_wr_t ioexp_hal_apply(uint8_t desired_light_bits);

// Піднімає чи опускає лінію скидання далекоміра (bit — IOEXP_BIT_XSHUT_*), світло лишається як підтверджене.
// IOEXP_WR_OK — запис підтверджено; IOEXP_WR_FAILED — шина не підтвердила чи мʼютекс зайнятий (розряд лишається як був);
// IOEXP_WR_UNAVAILABLE — розширювач недоступний.
ioexp_wr_t ioexp_hal_xshut(int bit, bool high);
