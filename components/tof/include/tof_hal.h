// HAL далекомірів (phase6-tof, ADR-0002, ADR-0003): драйвер VL53L0X, послідовність лінії скидання з новими адресами,
// задача sensors, знімок для control, повторна ініціалізація. Логіка — у tof_core.c.
#pragma once

#include <stdbool.h>
#include <stddef.h>

#include "esp_err.h"
#include "tof_core.h"

// Стартує задачу sensors (core 0, prio 3, період 50 мс; у Task WDT не підписана — sad.md §1, Decision override). Вона піднімає
// чотири далекоміри по одному (U7, U8, U9, U10) за документом 02 §4.7: лінія скидання через ioexp, пауза, перевірка моделі на
// 0x29, ініціалізація, нова адреса 0x30…0x33, безперервний режим; результат кожного — рядок журналу. Відмова одного не зупиняє
// решту; розширювач недоступний → усі в відмові з одним попередженням. Викликається після ioexp_start (перша операція на шині —
// запис нуля). ESP_FAIL — задачу не створено (захисту немає, ровер працює).
esp_err_t tof_start(void);

// Копія знімка (valid == false, доки задача не опублікувала перший). Для control і консолі.
void tof_snapshot_get(tof_view_t *out);

// Консоль `tof`: показ знімка (з позначкою «знімок застарів»); повертає довжину.
size_t tof_show_text(char *buf, size_t n);

// Консоль `tof reinit`: просить задачу sensors повернути відмовивші далекоміри (лише DISARMED, перевіряється й тут), чекає до
// 3 с і повертає текст відповіді; повертає довжину. Опитування решти на цей час призупиняється (spec AC-08).
size_t tof_reinit_text(char *buf, size_t n);
